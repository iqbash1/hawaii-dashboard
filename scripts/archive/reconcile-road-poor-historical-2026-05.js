#!/usr/bin/env node
/**
 * One-off reconciliation: extend road_poor_pct historical coverage to 2000.
 *
 * Background: FHWA HM-64 (Socrata 26bt-cq5y) publishes the full 2000-2024
 * series. state-data.js currently has 2007-2024 only. This script merges
 * 2000-2006 into state-data.js via build-state-data.js's exported fetcher.
 * Year-level merge preserves all existing 2007-2024 values.
 *
 * Companion to commit "road_poor_pct: narrative + validator + fyc config
 * for 2000-2024 extension" — that commit already wired the dataNote, the
 * rankHistoryNarrative.summary rewrite, the 20-year FYC exclusion, and the
 * per-metric YoY noisy-transition exemption.
 *
 * After this script runs, the standard regen sequence (recompute,
 * update-about-years, generate-og-pages, sync-qotd) propagates the new
 * years to data.js, the About registry, stubs, OG images, and CSV.
 *
 * Then move to scripts/archive/ per the sanctioned-writer rule.
 *
 * Usage: NODE_TLS_REJECT_UNAUTHORIZED=0 node scripts/reconcile-road-poor-historical-2026-05.js
 */

const fs = require('fs');
const path = require('path');
const bsd = require('./build-state-data.js');

const ROOT = path.join(__dirname, '..');
const OUT  = path.join(ROOT, 'js/state-data.js');
const ADD_YEARS = ['2000', '2001', '2002', '2003', '2004', '2005', '2006'];

async function main() {
    const src = fs.readFileSync(OUT, 'utf8');
    const m = src.match(/const\s+STATE_DATA\s*=\s*([\s\S]+);\s*$/);
    if (!m) throw new Error('Could not parse state-data.js');
    const existing = JSON.parse(m[1]);

    if (!existing.road_poor_pct?.data) {
        throw new Error('existing state-data.js has no road_poor_pct');
    }

    console.log('Fetching road_poor_pct from FHWA Socrata...');
    const fresh = await bsd.fetchers.road_poor_pct();
    if (!fresh?.data) throw new Error('Fetcher returned no data');

    let added = 0;
    let skipped = 0;
    for (const yr of ADD_YEARS) {
        if (!fresh.data[yr]) {
            console.log(`  ${yr}: source has no data (expected for 2010 and 2021 only); skip`);
            skipped++;
            continue;
        }
        if (existing.road_poor_pct.data[yr]) {
            console.log(`  ${yr}: already present in state-data.js; skip`);
            skipped++;
            continue;
        }
        const cell = fresh.data[yr];
        const stateCount = Object.keys(cell).filter(k => k !== 'name').length;
        const hi = cell['Hawaiʻi'];
        if (stateCount < 50) {
            console.log(`  ${yr}: only ${stateCount} states reporting; skip (full coverage required)`);
            skipped++;
            continue;
        }
        existing.road_poor_pct.data[yr] = cell;
        added++;
        console.log(`  ${yr}: added (${stateCount} states; HI = ${hi})`);
    }

    if (added === 0) {
        console.log('Nothing to add; state-data.js unchanged.');
        return;
    }

    // Resort each year's data alphabetically inside year keys + sort year keys
    // so that state-data.js maintains its existing internal order.
    const sortedYears = Object.keys(existing.road_poor_pct.data).sort();
    const reordered = {};
    for (const y of sortedYears) reordered[y] = existing.road_poor_pct.data[y];
    existing.road_poor_pct.data = reordered;

    // Alphabetically sort metric keys to match build-state-data.js output.
    const sortedKeys = Object.keys(existing).sort();
    const sorted = {};
    for (const k of sortedKeys) sorted[k] = existing[k];

    const timestamp = new Date().toISOString();
    const output = `// ============================================================
// Hawaiʻi Dashboard - All-State Time Series Data
//
// Auto-generated by: node scripts/build-state-data.js (with one-time
// backfill scripts contributing the historical metrics this fetcher
// does not cover; build-state-data.js MERGES with the existing file
// rather than overwriting, to preserve those backfilled metrics).
// Generated: ${timestamp}
//
// Contains per-state values across all available years.
// Structure: { slug: { source, calculation, data: { year: { state: val } } } }
// Values stored as decimals for percentages (0.35 = 35%).
// DC is excluded to match the dashboard methodology.
// ============================================================

const STATE_DATA = ${JSON.stringify(sorted, null, 2)};
`;

    fs.writeFileSync(OUT, output);
    console.log(`\nWrote state-data.js: ${added} years added, ${skipped} skipped.`);
}

main().catch(e => { console.error(e); process.exit(1); });
