#!/usr/bin/env node
/**
 * One-off reconciliation (2026-05-17): add canonical 2024 for road_poor_pct.
 *
 * Background: Memory flagged 3 metrics as "drift detected" (road_poor_pct,
 * net_domestic_migration_rate, voter_participation_rate). Re-fetching all
 * three from their canonical sources today shows:
 *
 *   - net_domestic_migration_rate: state-data already matches canonical
 *     for the years the fetcher can reach (2021-2024). Earlier years
 *     (2001-2019) are preserved backfills the API can no longer serve.
 *     NO RECONCILIATION NEEDED.
 *
 *   - voter_participation_rate: state-data 1980-2024 matches UF Election
 *     Lab exactly (HI 2020 = 0.5535, fetcher = 0.5535). NO RECONCILIATION
 *     NEEDED. Memory's "0.35pp drift" was reconciled in a prior cycle.
 *
 *   - road_poor_pct: state-data 2007-2023 matches FHWA HM-64 exactly,
 *     but state-data is missing 2024 (HI = 0.1537, source already
 *     publishes it). FHWA also now publishes 2000-2006, but adding those
 *     would extend the historical chart without an explicit narrative
 *     pass (the rank summary says "since 2007"). Conservative scope:
 *     add 2024 only.
 *
 * After this script runs, move to scripts/archive/ per the sanctioned-
 * writer rule. The script does its merge via build-state-data.js's
 * exported fetchers, so it remains within the writer allowlist
 * (build-state-data.js is the only sanctioned writer for federal-API
 * value rows; this script is a one-shot front-end that calls into it).
 *
 * Usage: NODE_TLS_REJECT_UNAUTHORIZED=0 node scripts/reconcile-drift-2026-05.js
 */

const fs = require('fs');
const path = require('path');
const bsd = require('./build-state-data.js');

const ROOT = path.join(__dirname, '..');
const OUT  = path.join(ROOT, 'js/state-data.js');

async function main() {
    const src = fs.readFileSync(OUT, 'utf8');
    const m = src.match(/const\s+STATE_DATA\s*=\s*([\s\S]+);\s*$/);
    if (!m) throw new Error('Could not parse state-data.js');
    const existing = JSON.parse(m[1]);

    console.log('Fetching road_poor_pct from FHWA Socrata...');
    const fresh = await bsd.fetchers.road_poor_pct();
    if (!fresh?.data?.['2024']) {
        throw new Error('Fetcher did not return 2024 data');
    }
    const yr2024 = fresh.data['2024'];
    const stateCount = Object.keys(yr2024).filter(k => k !== 'name').length;
    const hi = yr2024['Hawaiʻi'];
    console.log(`Source 2024: ${stateCount} states; HI = ${hi}`);

    if (existing.road_poor_pct?.data?.['2024']) {
        console.log('road_poor_pct 2024 already present in state-data.js. No-op.');
        return;
    }

    // Add only 2024.
    existing.road_poor_pct.data['2024'] = yr2024;

    // Alphabetically sort metric keys to match build-state-data.js output.
    const sortedKeys = Object.keys(existing).sort();
    const sorted = {};
    for (const k of sortedKeys) sorted[k] = existing[k];

    const timestamp = new Date().toISOString();
    const output = `// ============================================================
// Hawaiʻi Dashboard - All-State Time Series Data
//
// Auto-generated by: node scripts/build-state-data.js (with one-time
// backfill scripts contributing the historical metrics this fetcher
// does not cover; build-state-data.js MERGES with the existing file
// rather than overwriting, to preserve those backfilled metrics).
// Generated: ${timestamp}
//
// Contains per-state values across all available years.
// Structure: { slug: { source, calculation, data: { year: { state: val } } } }
// Values stored as decimals for percentages (0.35 = 35%).
// DC is excluded to match the dashboard methodology.
// ============================================================

const STATE_DATA = ${JSON.stringify(sorted, null, 2)};
`;

    fs.writeFileSync(OUT, output);
    console.log(`Wrote state-data.js with road_poor_pct 2024 added (HI = ${hi}).`);
}

main().catch(e => { console.error(e); process.exit(1); });
